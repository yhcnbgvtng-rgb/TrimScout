#!/usr/bin/env bash
# Regenerates the install patches and manifest.txt from the working tree. Run from the repo root, with the files final:
#   bash docs/box-patches/2026-10-27-sweep-guards/make-patches.sh [BASE_REF]      (BASE_REF defaults to origin/main = the code before this change)
# The install test (scripts/box/sweep-guards-install.test.mjs) fails if these are stale.
set -euo pipefail
BASE="${1:-origin/main}"
D=docs/box-patches/2026-10-27-sweep-guards
PATCHED=(scripts/box/inventory-sync.mjs scripts/box/syncRun.js scripts/box/syncSweep.js scrapers/lightsail-crawler/src/deals_api_server.js)
for f in "${PATCHED[@]}"; do
  git diff "$BASE" --no-prefix -U3 -- "$f" > "$D/$(basename "$f").patch"
done
{
  echo "# md5  role  file   (generated by make-patches.sh; BASE = $BASE)"
  for f in "${PATCHED[@]}"; do
    echo "$(git show "$BASE:$f" | md5sum | cut -d' ' -f1)  BASE   $(basename "$f")"
    echo "$(md5sum < "$f" | cut -d' ' -f1)  FINAL  $(basename "$f")"
  done
  echo "$(git show "$BASE:scrapers/lightsail-crawler/src/inventorySweep.js" | md5sum | cut -d' ' -f1)  BASE   inventorySweep.js"
  echo "$(md5sum < scrapers/lightsail-crawler/src/inventorySweep.js | cut -d' ' -f1)  FINAL  inventorySweep.js"
  echo "$(md5sum < scripts/box/syncSweepGuard.js | cut -d' ' -f1)  FINAL  syncSweepGuard.js"
} > "$D/manifest.txt"
node - "$D" <<'JS'
const fs = require("node:fs");
const d = process.argv[2];
const block = fs.readFileSync(`${d}/manifest.txt`, "utf8").trimEnd();
const s = fs.readFileSync(`${d}/STEPS.md`, "utf8");
const next = "<!-- MD5S:START -->\n```\n" + block + "\n```\n<!-- MD5S:END -->";
fs.writeFileSync(`${d}/STEPS.md`, s.replace(/<!-- MD5S:START -->[\s\S]*?<!-- MD5S:END -->/, () => next));
JS
echo "wrote $(ls $D/*.patch | wc -l) patches, manifest.txt and the md5 table in STEPS.md"
